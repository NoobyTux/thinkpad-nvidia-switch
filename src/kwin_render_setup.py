"""Install/remove an optional, user-scoped KWin Intel-only restriction.

Two KWin settings are needed to keep the desktop off the NVIDIA GPU:

* ``KWIN_RENDER_NODES`` limits the *render* nodes (``renderDN``) KWin opens for drawing.
* ``KWIN_DRM_DEVICES`` limits the *display* devices (``cardN``) KWin opens. Without it
  KWin opens every GPU on the seat, so a driver that registers a display device for
  NVIDIA (``nvidia-drm`` with modeset) stays in use and cannot be unloaded.

Both variables treat ':' as a list separator. PCI by-path symlinks contain ':', so
install app-owned, colon-free symlinks *to* the stable udev paths. They remain correct
when the kernel renumbers cardN/renderD nodes.

This only changes KWin's environment, not the environment of Steam or games.
Never restart KWin or force any NVIDIA kernel module unload here.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

MARKER = '# Managed by ThinkPad Nvidia Switch; do not edit this file.\n'
DROPIN_NAME = '90-thinkpad-nvidia-switch-intel-render.conf'
LINK_NAME = 'kwin-intel-render'
CARD_LINK_NAME = 'kwin-intel-card'
_BDF = r'[0-9a-fA-F]{4}:[0-9a-fA-F]{2}:[0-9a-fA-F]{2}\.[0-7]'
BDF_RE = re.compile(rf'^pci-({_BDF})-render$')
CARD_RE = re.compile(rf'^pci-({_BDF})-card$')
MIN_KWIN_VERSION = (6, 7, 4)


def _safe_value(path: Path) -> str:
    value = str(path)
    # Avoid list splitting and systemd unit-value escaping surprises. Normal
    # home paths, including those with spaces, are handled by quoting.
    if any(c in value for c in ':"\\\r\n%'):
        raise ValueError('Home directory has characters unsafe for the KWin render-node setting')
    return value


def systemd_content(alias: Path, card_alias: Path | None = None) -> str:
    """Drop-in text. Without *card_alias* this is the format written by releases before 2.6.9."""
    lines = ['[Service]', 'Environment="KWIN_RENDER_NODES=' + _safe_value(alias) + '"']
    if card_alias is not None:
        lines.append('Environment="KWIN_DRM_DEVICES=' + _safe_value(card_alias) + '"')
    lines.append('Environment="__EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/50_mesa.json"')
    return MARKER + '\n'.join(lines) + '\n'


def kwin_supported(which=shutil.which, run=subprocess.run) -> bool:
    exe = which('kwin_wayland')
    if not exe:
        return False
    try:
        result = run([exe, '--version'], capture_output=True, text=True, timeout=5, check=False)
        version = re.search(r'(?<!\d)(\d+)\.(\d+)\.(\d+)(?!\d)', result.stdout + '\n' + result.stderr)
        return bool(result.returncode == 0 and version and tuple(map(int, version.groups())) >= MIN_KWIN_VERSION)
    except (OSError, subprocess.TimeoutExpired):
        return False


def _find_intel_link(kind: str, pattern: re.Pattern, by_path: Path, pci_devices: Path) -> Path:
    """Require *one* working PCI Intel graphics path of this kind; never guess IDs."""
    candidates: list[Path] = []
    for link in sorted(by_path.glob(f'pci-*-{kind}')):
        match = pattern.fullmatch(link.name)
        if not match or not link.is_symlink() or not link.exists():
            continue
        pci = pci_devices / match.group(1)
        try:
            vendor = (pci / 'vendor').read_text().strip().lower()
            device_class = (pci / 'class').read_text().strip().lower()
        except OSError:
            continue
        if vendor == '0x8086' and device_class.startswith('0x03'):
            candidates.append(link)
    if len(candidates) != 1:
        raise ValueError(f'Expected one Intel graphics {kind} path; detected {len(candidates)}. KWin is unchanged.')
    return candidates[0]


def find_intel_render_link(by_path: Path = Path('/dev/dri/by-path'),
                           pci_devices: Path = Path('/sys/bus/pci/devices')) -> Path:
    return _find_intel_link('render', BDF_RE, by_path, pci_devices)


def find_intel_card_link(by_path: Path = Path('/dev/dri/by-path'),
                         pci_devices: Path = Path('/sys/bus/pci/devices')) -> Path:
    return _find_intel_link('card', CARD_RE, by_path, pci_devices)


def locations(home: Path) -> tuple[Path, Path]:
    alias = home / '.config' / 'thinkpad-nvidia-switch' / LINK_NAME
    dropin = home / '.config' / 'systemd' / 'user' / 'plasma-kwin_wayland.service.d' / DROPIN_NAME
    return alias, dropin


def card_location(home: Path) -> Path:
    return home / '.config' / 'thinkpad-nvidia-switch' / CARD_LINK_NAME


def _check_alias(alias: Path, pattern: re.Pattern, by_path: Path) -> None:
    """Refuse to replace anything that is not an earlier alias created by this app."""
    if alias.is_symlink():
        old_target = alias.readlink()
        # A prior app installation points only to a PCI udev link of the same kind.
        if not (old_target.is_absolute() and pattern.fullmatch(old_target.name)
                and old_target.parent == by_path):
            raise ValueError(f'Refusing to replace an unrelated symlink: {alias}')
    elif alias.exists():
        raise ValueError(f'Refusing to replace an existing path: {alias}')


def _write_alias(alias: Path, target: Path) -> None:
    next_alias = alias.with_name(alias.name + '.tmp')
    if next_alias.exists() or next_alias.is_symlink():
        raise ValueError(f'Temporary symlink path already exists: {next_alias}')
    next_alias.symlink_to(target)
    os.replace(next_alias, alias)


def install(home: Path, by_path: Path = Path('/dev/dri/by-path'),
            pci_devices: Path = Path('/sys/bus/pci/devices'),
            mesa_json: Path = Path('/usr/share/glvnd/egl_vendor.d/50_mesa.json')) -> str:
    home = home.expanduser().resolve()
    alias, dropin = locations(home)
    card_alias = card_location(home)
    content = systemd_content(alias, card_alias)
    if not mesa_json.is_file():
        raise ValueError('Mesa EGL vendor file is missing; KWin is unchanged')
    target = find_intel_render_link(by_path, pci_devices)
    card_target = find_intel_card_link(by_path, pci_devices)
    if (BDF_RE.fullmatch(target.name).group(1).lower()
            != CARD_RE.fullmatch(card_target.name).group(1).lower()):
        raise ValueError('The Intel render and display paths belong to different devices. KWin is unchanged.')

    # Check everything before changing anything. Do not overwrite files with the same
    # name unless they were created by us (an earlier release's drop-in is ours).
    if dropin.exists() and not dropin.read_text().startswith(MARKER):
        raise ValueError(f'Refusing to overwrite an existing user-owned KWin setting: {dropin}')
    _check_alias(alias, BDF_RE, by_path)
    _check_alias(card_alias, CARD_RE, by_path)

    alias.parent.mkdir(parents=True, exist_ok=True)
    dropin.parent.mkdir(parents=True, exist_ok=True)
    # If installing from v2.6.1, the manual 70-intel-render.conf experiment
    # stays intact. Our 90- drop-in supersedes it while installed.
    _write_alias(alias, target)
    _write_alias(card_alias, card_target)
    next_dropin = dropin.with_name(dropin.name + '.tmp')
    if next_dropin.exists() or next_dropin.is_symlink():
        raise ValueError(f'Temporary KWin drop-in path already exists: {next_dropin}')
    try:
        next_dropin.write_text(content)
        next_dropin.chmod(0o644)
        os.replace(next_dropin, dropin)
    finally:
        next_dropin.unlink(missing_ok=True)
    return (f'Intel render node: {target} (via {alias}); Intel display device: {card_target} (via {card_alias}); '
            f'KWin drop-in: {dropin}')


def _remove_alias(alias: Path, pattern: re.Pattern, by_path: Path, what: str) -> None:
    if alias.is_symlink():
        dest = alias.readlink()
        if (dest.is_absolute() and dest.parent == by_path and pattern.fullmatch(dest.name)):
            alias.unlink()
        else:
            raise ValueError(f'KWin Intel {what} alias was modified; leaving it untouched: {alias}')


def uninstall(home: Path, by_path: Path = Path('/dev/dri/by-path')) -> str:
    home = home.expanduser().resolve()
    alias, dropin = locations(home)
    card_alias = card_location(home)
    # Protect files the user may have edited after installation. A replaced
    # configuration is no longer ours to remove automatically. Releases before
    # 2.6.9 wrote the drop-in without the display-device line; both forms are ours.
    expected = {systemd_content(alias, card_alias), systemd_content(alias)}
    if dropin.exists():
        if dropin.read_text() not in expected:
            raise ValueError(f'KWin drop-in was modified; leaving it untouched: {dropin}')
        dropin.unlink()
    _remove_alias(alias, BDF_RE, by_path, 'render')
    _remove_alias(card_alias, CARD_RE, by_path, 'display')
    # Do not remove unrelated 50-mesa-only.conf or 70-intel-render.conf.
    return 'Removed only the app-managed KWin render-node restriction.'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('install', 'uninstall'))
    args = parser.parse_args()
    home = Path.home()
    try:
        if args.action == 'install':
            if not kwin_supported():
                print('KWin Intel-only workaround skipped (KWin Wayland >= 6.7.4 was not detected).')
                return 0
            message = install(home)
            print('KWin Intel-only workaround installed: ' + message)
            print('Log out and log back in to activate it; Steam is not restricted. Monitors wired to NVIDIA do not work in the KDE session while it is installed.')
        else:
            print(uninstall(home))
            print('Log out and log back in to remove the KWin-only restriction.')
    except (OSError, ValueError) as exc:
        print(f'KWin render workaround: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
